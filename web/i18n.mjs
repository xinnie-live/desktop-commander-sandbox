export function detectLanguage(languages = []) {
  const preferred = Array.isArray(languages) ? languages[0] : languages;
  return /^zh(?:-|$)/i.test(String(preferred || '')) ? 'zh' : 'en';
}

export function translateText(value, language = 'en') {
  const text = String(value ?? '');
  if (language === 'zh') return text;
  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const leading = match?.[1] || '';
  const content = match?.[2] || text;
  const trailing = match?.[3] || '';
  if (TRANSLATIONS.has(content)) return `${leading}${TRANSLATIONS.get(content)}${trailing}`;
  if (content.includes('；')) {
    const clauses = content.split('；').map((clause) => translateText(clause, language));
    if (clauses.every((clause) => !clause.includes('This message is available in Chinese.'))) {
      return `${leading}${clauses.join('; ')}${trailing}`;
    }
  }
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(content)) {
      let translated = content.replace(pattern, replacement);
      translated = translated.replace(/^失败/, 'Failed');
      translated = translated.replaceAll(' · 当前', ' · current').replaceAll(' · 文件夹不存在', ' · folder missing');
      return `${leading}${translated}${trailing}`;
    }
  }
  return /[\p{Script=Han}]/u.test(content)
    ? `${leading}This message is available in Chinese. Switch the interface language to 中文 for details.${trailing}`
    : text;
}

export function installLanguagePicker({
  documentRef = document,
  storage,
  languages = globalThis.navigator?.languages?.length ? globalThis.navigator.languages : [globalThis.navigator?.language],
} = {}) {
  const key = 'rds-ui-language';
  let languageStorage = storage;
  try { languageStorage ??= globalThis.localStorage; } catch { /* Storage may be unavailable for this browser origin. */ }
  let stored;
  try { stored = languageStorage?.getItem(key); } catch { /* Continue with browser-language detection when storage is unavailable. */ }
  let language = stored === 'zh' || stored === 'en' ? stored : detectLanguage(languages);
  const originals = new WeakMap();
  const applied = new WeakMap();
  const attributeOriginals = new WeakMap();
  const attributeApplied = new WeakMap();
  const watchedAttributes = new Set(['aria-label', 'aria-description', 'title', 'placeholder', 'alt']);
  let pickerButton;

  function excluded(node) {
    const parent = node.nodeType === 1 ? node : node.parentElement;
    return parent?.closest('pre, script, style, [data-i18n-ignore]');
  }

  function applyText(node, source = node.nodeValue) {
    if (excluded(node)) return;
    if (!originals.has(node) || applied.get(node) !== source) originals.set(node, source);
    const next = translateText(originals.get(node), language);
    applied.set(node, next);
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  function applyAttributes(element) {
    if (element.hasAttribute('data-i18n-ignore')) return;
    for (const name of watchedAttributes) {
      if (!element.hasAttribute(name)) continue;
      const current = element.getAttribute(name);
      let sourceMap = attributeOriginals.get(element);
      let appliedMap = attributeApplied.get(element);
      if (!sourceMap) { sourceMap = new Map(); attributeOriginals.set(element, sourceMap); }
      if (!appliedMap) { appliedMap = new Map(); attributeApplied.set(element, appliedMap); }
      if (!sourceMap.has(name) || appliedMap.get(name) !== current) sourceMap.set(name, current);
      const next = translateText(sourceMap.get(name), language);
      appliedMap.set(name, next);
      if (current !== next) element.setAttribute(name, next);
    }
  }

  function translateSubtree(root) {
    if (!root || excluded(root)) return;
    if (root.nodeType === 3) { applyText(root); return; }
    if (root.nodeType !== 1 && root !== documentRef) return;
    if (root.nodeType === 1) applyAttributes(root);
    const walker = documentRef.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) applyText(node);
    if (root.querySelectorAll) for (const element of root.querySelectorAll('*')) applyAttributes(element);
  }

  function updatePicker() {
    documentRef.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    documentRef.title = language === 'zh' ? 'Desktop Commander Sandbox · 本机控制' : 'Desktop Commander Sandbox · Local Control';
    if (pickerButton) {
      pickerButton.textContent = language === 'zh' ? 'English' : '中文';
      pickerButton.setAttribute('aria-label', language === 'zh' ? '切换界面语言为英文' : 'Switch interface language to Chinese');
    }
  }

  function setLanguage(nextLanguage, persist = true) {
    language = nextLanguage === 'zh' ? 'zh' : 'en';
    if (persist) {
      try { languageStorage?.setItem(key, language); } catch { /* Keep the current page usable when storage is unavailable. */ }
    }
    updatePicker();
    translateSubtree(documentRef.body);
    return language;
  }

  translateSubtree(documentRef.body);
  pickerButton = documentRef.querySelector('#language-toggle');
  if (pickerButton) {
    pickerButton.addEventListener('click', () => setLanguage(language === 'zh' ? 'en' : 'zh'));
  }
  updatePicker();

  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') {
        const current = record.target.nodeValue;
        if (applied.get(record.target) !== current) applyText(record.target, current);
      } else if (record.type === 'attributes') {
        if (!watchedAttributes.has(record.attributeName)) continue;
        const element = record.target;
        const current = element.getAttribute(record.attributeName);
        const appliedMap = attributeApplied.get(element);
        if (appliedMap?.get(record.attributeName) !== current) applyAttributes(element);
      } else {
        for (const node of record.addedNodes) translateSubtree(node);
      }
    }
  });
  observer.observe(documentRef.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...watchedAttributes] });
  return { get language() { return language; }, setLanguage };
}
